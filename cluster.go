type clusterJoinRequest struct {
	NodeID string `json:"node_id"` // joining node's own identity
	Name   string `json:"name"`
	URL    string `json:"url"` // public base URL of the joining node
}

type clusterJoinResponse struct {
	NodeID   string        `json:"node_id"`
	NodeName string        `json:"node_name"`
	Token    string        `json:"token"`
	Peers    []clusterPeer `json:"peers"`
}

type clusterPeer struct {
	ID    string `json:"id"`
	Name  string `json:"name"`
	URL   string `json:"url"`
	Token string `json:"token"`
}

// handleClusterInvite generates a one-time invite token (operator, this node).
func handleClusterInvite(c *gin.Context) {
	token := randomHexKey(24)
	pendingInvitesMu.Lock()
	if len(pendingInvites) > 64 {
		pendingInvites = make(map[string]time.Time)
	}
	pendingInvites[token] = time.Now().Add(15 * time.Minute)
	pendingInvitesMu.Unlock()

	settingsMutex.RLock()
	name := GlobalSettings.ServerName
	settingsMutex.RUnlock()

	addLog("CLUSTER", "INVITE_GENERATED (valid 15 minutes)")
	c.JSON(http.StatusOK, APIResponse{Status: "success", Data: map[string]interface{}{
		"invite_token": token,
		"expires_at":   time.Now().Add(15 * time.Minute),
		"node_name":    name,
	}})
}

// handleClusterJoinOperator is the operator-facing entry on the JOINING node:
// it dials the inviting node with the invite token and bootstraps the mesh.
func handleClusterJoinOperator(c *gin.Context) {
	var req struct {
		URL         string `json:"url" binding:"required"`
		InviteToken string `json:"invite_token" binding:"required"`
		Name        string `json:"name"`
	}
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, APIResponse{Status: "error", Message: err.Error()})
		return
	}
	req.URL = normalizeNodeURL(req.URL)
	if req.URL == "" {
		c.JSON(http.StatusBadRequest, APIResponse{Status: "error", Message: "INVALID_URL"})
		return
	}

	settingsMutex.RLock()
	selfName := GlobalSettings.ServerName
	settingsMutex.RUnlock()
	if req.Name != "" {
		selfName = req.Name
	}

	joinURL := req.URL + "/cluster/join"

	// dialJoin POSTs the join request signed with the invite token.
	dialJoin := func() (*http.Response, []byte, error) {
		joinBody, _ := json.Marshal(clusterJoinRequest{NodeID: localNodeID(), Name: selfName, URL: externalNodeURL()})
		joinReq, err := http.NewRequest(http.MethodPost, joinURL, bytes.NewReader(joinBody))
		if err != nil {
			return nil, nil, err
		}
		joinReq.Header.Set("X-Invite-Token", req.InviteToken)
		joinReq.Header.Set("Content-Type", "application/json")
		resp, err := clusterHTTPClient.Do(joinReq)
		if err != nil {
			return nil, nil, err
		}
		body, _ := io.ReadAll(resp.Body)
		resp.Body.Close()
		return resp, body, nil
	}

	resp, respBody, err := dialJoin()
	if err != nil {
		c.JSON(http.StatusBadGateway, APIResponse{Status: "error", Message: "JOIN_FAILED: " + err.Error()})
		return
	}
	if resp.StatusCode == http.StatusBadRequest && bytes.Contains(respBody, []byte("DUPLICATE_NODE_ID")) {
		// The peer's own node_id matches ours — almost certainly a node
		// deployed by copying another node's data directory. Reissue the
		// identity and retry once.
		regenerateLocalNodeID()
		resp, respBody, err = dialJoin()
		if err != nil {
			c.JSON(http.StatusBadGateway, APIResponse{Status: "error", Message: "JOIN_FAILED: " + err.Error()})
			return
		}
	}
	if resp.StatusCode != http.StatusOK {
		c.JSON(http.StatusBadGateway, APIResponse{Status: "error", Message: fmt.Sprintf("JOIN_REJECTED (%d): %s", resp.StatusCode, string(respBody))})
		return
	}

	var joinResp clusterJoinResponse
	if err := json.Unmarshal(respBody, &joinResp); err != nil || joinResp.Token == "" {
		c.JSON(http.StatusInternalServerError, APIResponse{Status: "error", Message: "JOIN_BAD_RESPONSE"})
		return
	}

	// Store the inviting node as our first peer.
	upsertPeer(ClusterNode{
		ID: joinResp.NodeID, Name: joinResp.NodeName, URL: req.URL,
		Token: joinResp.Token, Status: "online", LastSeen: time.Now(), CreatedAt: time.Now(),
	})
	// Introduce the remaining mesh peers delivered in the join response.
	for _, p := range joinResp.Peers {
		upsertPeer(ClusterNode{ID: p.ID, Name: p.Name, URL: p.URL, Token: p.Token, CreatedAt: time.Now()})
	}

	addLog("CLUSTER", fmt.Sprintf("JOINED_CLUSTER: %s (%s)", joinResp.NodeName, req.URL))

	// Pull the initial state snapshot from the inviting node.
	var peer ClusterNode
	if err := db.First(&peer, "id = ?", joinResp.NodeID).Error; err == nil {
		if snapResp, err := clusterRequest(peer, http.MethodGet, "/cluster/snapshot", nil); err == nil {
			body, _ := io.ReadAll(snapResp.Body)
			snapResp.Body.Close()
			if snapResp.StatusCode == http.StatusOK {
				applyClusterSnapshot(body)
				addLog("CLUSTER", "SNAPSHOT_APPLIED")
			}
		}
	}

	c.JSON(http.StatusOK, APIResponse{Status: "success", Message: "JOINED_CLUSTER", Data: clusterStatusData()})
}

// handleClusterJoin runs on the INVITING node; authenticated by the invite
// token in the X-Invite-Token header.
func handleClusterJoin(c *gin.Context) {
	invite := c.GetHeader("X-Invite-Token")
	// Validate but do not consume yet: a rejected join (duplicate node id)
	// must leave the invite intact so the joining node can retry.
	pendingInvitesMu.Lock()
	expiry, ok := pendingInvites[invite]
	pendingInvitesMu.Unlock()
	if !ok || time.Now().After(expiry) {
		c.JSON(http.StatusUnauthorized, APIResponse{Status: "error", Message: "INVALID_OR_EXPIRED_INVITE"})
		return
	}

	var req clusterJoinRequest
	if err := c.ShouldBindJSON(&req); err != nil || req.URL == "" {
		c.JSON(http.StatusBadRequest, APIResponse{Status: "error", Message: "NAME_AND_URL_REQUIRED"})
		return
	}
	req.URL = normalizeNodeURL(req.URL)
	// The joining node identifies itself; the pair token is what actually
	// authenticates it, so reuse of an ID only re-binds the peer row.
	if req.NodeID == "" || req.NodeID == localNodeID() {
		// Identical IDs mean both sides share one data directory (copied
		// deployment); the joining node regenerates and retries on its side.
		c.JSON(http.StatusBadRequest, APIResponse{Status: "error", Message: "DUPLICATE_NODE_ID: joining node shares this node's data directory - each node needs its own PRTS_DB_PATH"})
		return
	}

	// All checks passed: consume the one-time invite.
	pendingInvitesMu.Lock()
	delete(pendingInvites, invite)
	pendingInvitesMu.Unlock()

	pairToken := randomHexKey(32)
	newNode := ClusterNode{
		ID: req.NodeID, Name: req.Name, URL: req.URL,
		Token: pairToken, Status: "online", LastSeen: time.Now(), CreatedAt: time.Now(),
	}
	upsertPeer(newNode)
	addLog("CLUSTER", fmt.Sprintf("NODE_JOINED: %s (%s)", req.Name, req.URL))

	// Introduce the newcomer to existing peers with fresh pair tokens and
	// hand the newcomer the same introductions in the response.
	var existing []ClusterNode
	db.Where("id != ? AND id != ?", localNodeID(), newNode.ID).Find(&existing)

	response := clusterJoinResponse{
		NodeID:   localNodeID(),
		NodeName: selfRow.Name,
		Token:    pairToken,
		Peers:    make([]clusterPeer, 0, len(existing)),
	}
	for _, p := range existing {
		meshToken := randomHexKey(32)
		// Tell the existing peer about the newcomer.
		introNewcomer, _ := json.Marshal(clusterPeer{ID: newNode.ID, Name: newNode.Name, URL: newNode.URL, Token: meshToken})
		db.Create(&ClusterEvent{TargetNode: p.ID, Type: "node_new", Payload: string(introNewcomer), CreatedAt: time.Now()})
		// Tell the newcomer about the existing peer (via join response).
		response.Peers = append(response.Peers, clusterPeer{ID: p.ID, Name: p.Name, URL: p.URL, Token: meshToken})
	}

	c.JSON(http.StatusOK, response)
}

// handleClusterKicked is a best-effort notification to a removed node.
func handleClusterKicked(c *gin.Context) {
	peer := c.MustGet("cluster_peer").(ClusterNode)
	addLog("CLUSTER", fmt.Sprintf("NOTIFIED_REMOVAL: %s", peer.Name))
	db.Delete(&ClusterNode{}, "id = ?", peer.ID)
	c.JSON(http.StatusOK, APIResponse{Status: "success"})
}

func normalizeNodeURL(raw string) string {
	raw = bytesNewTrimmed(raw)
	for len(raw) > 0 && raw[len(raw)-1] == '/' {
		raw = raw[:len(raw)-1]
	}
	if raw == "" {
		return ""
	}
	if !bytesHasScheme(raw) {
		raw = "http://" + raw
	}
	return raw
}

func bytesNewTrimmed(s string) string {
	start := 0
	end := len(s)
	for start < end && (s[start] == ' ' || s[start] == '\t') {
		start++
	}
	for end > start && (s[end-1] == ' ' || s[end-1] == '\t' || s[end-1] == '\n' || s[end-1] == '\r') {
		end--
	}
	return s[start:end]
}

func bytesHasScheme(s string) bool {
	for i := 0; i < len(s); i++ {
		if s[i] == ':' {
			return i > 0 && i <= 8 && (s[:i] == "http" || s[:i] == "https")
		}
		if s[i] == '/' {
			return false
		}
	}
	return false
}

// externalNodeURL is the URL this node advertises to peers.
func externalNodeURL() string {
	if v, ok := kvGet("node_url"); ok && v != "" {
		return v
	}
	addr := envOrDefault("PRTS_ADDR", ":8083")
	host := envOrDefault("PRTS_PUBLIC_HOST", "")
	if host == "" {
		host = "127.0.0.1"
	}
	if len(addr) > 0 && addr[0] == ':' {
		return normalizeNodeURL(fmt.Sprintf("http://%s%s", host, addr))
	}
	return normalizeNodeURL("http://" + addr)
}

func upsertPeer(node ClusterNode) {
	var existing ClusterNode
	if err := db.First(&existing, "id = ?", node.ID).Error; err == nil {
		updates := map[string]interface{}{"name": node.Name, "url": node.URL}
		if node.Token != "" {
			updates["token"] = node.Token
		}
		if node.Status != "" {
			updates["status"] = node.Status
		}
		if !node.LastSeen.IsZero() {
			updates["last_seen"] = node.LastSeen
		}
		db.Model(&existing).Updates(updates)
		return
	}
	db.Create(&node)
}


// clusterAuthRequired authenticates internal peer requests via the pair token.
// The authenticated peer row is stored in the context.
func clusterAuthRequired() gin.HandlerFunc {
	return func(c *gin.Context) {
		nodeID := c.GetHeader("X-Node-ID")
		sig := c.GetHeader("X-Node-Sign")
		ts := c.GetHeader("X-Node-Timestamp")
		if nodeID == "" || sig == "" || nodeID == localNodeID() {
			c.AbortWithStatusJSON(http.StatusUnauthorized, APIResponse{Status: "error", Message: "CLUSTER_AUTH_REQUIRED"})
			return
		}
		body, err := io.ReadAll(c.Request.Body)
		if err != nil {
			c.AbortWithStatusJSON(http.StatusBadRequest, APIResponse{Status: "error", Message: "BAD_BODY"})
			return
		}
		c.Request.Body = io.NopCloser(bytes.NewReader(body))

		tsInt, err := strconv.ParseInt(ts, 10, 64)
		if err != nil || time.Since(time.Unix(tsInt, 0)) > beaconTimestampWindow || time.Since(time.Unix(tsInt, 0)) < -beaconTimestampWindow {
			c.AbortWithStatusJSON(http.StatusUnauthorized, APIResponse{Status: "error", Message: "CLUSTER_AUTH_FAILED"})
			return
		}

		var peer ClusterNode
		if err := db.First(&peer, "id = ?", nodeID).Error; err != nil {
			c.AbortWithStatusJSON(http.StatusUnauthorized, APIResponse{Status: "error", Message: "UNKNOWN_NODE"})
			return
		}
		expected := clusterSignString(peer.Token, ts, body)
		given, err := hex.DecodeString(sig)
		if err != nil {
			c.AbortWithStatusJSON(http.StatusUnauthorized, APIResponse{Status: "error", Message: "CLUSTER_AUTH_FAILED"})
			return
		}
		expectedBytes, _ := hex.DecodeString(expected)
		if !hmac.Equal(given, expectedBytes) {
			addLog("SEC", fmt.Sprintf("CLUSTER_AUTH_FAILED: node %s", nodeID))
			c.AbortWithStatusJSON(http.StatusUnauthorized, APIResponse{Status: "error", Message: "CLUSTER_AUTH_FAILED"})
			return
		}
		c.Set("cluster_peer", peer)
		c.Next()
	}
}

func handleClusterHeartbeat(c *gin.Context) {
	peer := c.MustGet("cluster_peer").(ClusterNode)
	clusterMarkPeer(&peer, true)
	c.JSON(http.StatusOK, APIResponse{Status: "success"})
}

func handleClusterEvents(c *gin.Context) {
	var req struct {
		Events []clusterEventWire `json:"events" binding:"required"`
	}
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, APIResponse{Status: "error", Message: err.Error()})
		return
	}
	accepted := 0
	for _, e := range req.Events {
		if e.Payload == nil {
			continue
		}
		applyClusterEvent(e.Type, *e.Payload)
		accepted++
	}
	c.JSON(http.StatusOK, APIResponse{Status: "success", Data: map[string]int{"accepted": accepted}})
}

type clusterSnapshot struct {
	Node      ClusterNode `json:"node"`
	Beacons   []Client    `json:"beacons"`
	Listeners []Listener  `json:"listeners"`
	Tasks     []Task      `json:"tasks"`
}

func handleClusterSnapshot(c *gin.Context) {
	var beacons []Client
	db.Find(&beacons)
	var listeners []Listener
	db.Find(&listeners)
	var tasks []Task
	db.Order("created_at desc").Limit(200).Find(&tasks)

	c.JSON(http.StatusOK, clusterSnapshot{
		Node:      ClusterNode{ID: localNodeID(), Name: selfRow.Name, URL: externalNodeURL()},
		Beacons:   beacons,
		Listeners: listeners,
		Tasks:     tasks,
	})
}

func applyClusterSnapshot(body []byte) {
	var snap clusterSnapshot
	if err := json.Unmarshal(body, &snap); err != nil {
		return
	}
	for _, b := range snap.Beacons {
		upsertClientReplica(b)
	}
	for _, l := range snap.Listeners {
		upsertListenerReplica(l)
	}
	for _, t := range snap.Tasks {
		upsertTaskReplica(t)
	}
}


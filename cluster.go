func clusterStatusData() map[string]interface{} {
	var peers []ClusterNode
	db.Where("id != ?", localNodeID()).Order("created_at asc").Find(&peers)
	for i := range peers {
		peers[i].Token = ""
	}
	var queued int64
	db.Model(&ClusterEvent{}).Where("sent_at IS NULL").Count(&queued)

	self := selfRow
	self.URL = externalNodeURL()
	return map[string]interface{}{
		"self":           self,
		"peers":          peers,
		"pending_events": queued,
	}
}

func handleClusterStatus(c *gin.Context) {
	c.JSON(http.StatusOK, APIResponse{Status: "success", Data: clusterStatusData()})
}

// handleClusterSetURL sets the public URL this node advertises to peers.
func handleClusterSetURL(c *gin.Context) {
	var req struct {
		URL string `json:"url" binding:"required"`
	}
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, APIResponse{Status: "error", Message: err.Error()})
		return
	}
	url := normalizeNodeURL(req.URL)
	if url == "" {
		c.JSON(http.StatusBadRequest, APIResponse{Status: "error", Message: "INVALID_URL"})
		return
	}
	kvSet("node_url", url)
	addLog("CLUSTER", "NODE_URL_SET: "+url)
	c.JSON(http.StatusOK, APIResponse{Status: "success", Message: "NODE_URL_SET"})
}

func handleClusterRemoveNode(c *gin.Context) {
	id := c.Param("id")
	var peer ClusterNode
	if err := db.First(&peer, "id = ?", id).Error; err != nil {
		c.JSON(http.StatusNotFound, APIResponse{Status: "error", Message: "NODE_NOT_FOUND"})
		return
	}

	// Best-effort notification so the removed node drops the pair itself.
	if resp, err := clusterRequest(peer, http.MethodPost, "/cluster/kicked", nil); err == nil {
		resp.Body.Close()
	}

	db.Delete(&ClusterNode{}, "id = ?", id)
	db.Where("target_node = ?", id).Delete(&ClusterEvent{})
	addLog("CLUSTER", fmt.Sprintf("NODE_REMOVED: %s (%s)", peer.Name, peer.URL))
	c.JSON(http.StatusOK, APIResponse{Status: "success", Message: "NODE_REMOVED"})
}

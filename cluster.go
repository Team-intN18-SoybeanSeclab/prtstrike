const (
	clusterHeartbeatInterval = 30 * time.Second
	clusterOfflineAfter      = 90 * time.Second
	clusterEventInterval     = 2 * time.Second
	clusterEventBatch        = 100
	clusterEventMaxAge       = 24 * time.Hour
	clusterHTTPTimeout       = 10 * time.Second
)

var (
	localNodeIDCached string
	localNodeMu       sync.Mutex

	clusterHTTPClient = &http.Client{Timeout: clusterHTTPTimeout}

	// pendingInvites: one-time join tokens generated by the operator.
	pendingInvites   = make(map[string]time.Time)
	pendingInvitesMu sync.Mutex

	// selfRow is the local node's ClusterNode (Status = "self").
	selfRow ClusterNode
)

func localNodeID() string {
	localNodeMu.Lock()
	defer localNodeMu.Unlock()
	return localNodeIDLocked()
}

func localNodeIDLocked() string {
	if localNodeIDCached != "" {
		return localNodeIDCached
	}
	if id, ok := kvGet("node_id"); ok {
		localNodeIDCached = id
	} else {
		localNodeIDCached = uuid.NewString()
		kvSet("node_id", localNodeIDCached)
	}
	settingsMutex.RLock()
	name := GlobalSettings.ServerName
	settingsMutex.RUnlock()
	if name == "" {
		name = "PRTSTRIKE"
	}
	selfRow = ClusterNode{ID: localNodeIDCached, Name: name, Status: "self"}
	return localNodeIDCached
}

// regenerateLocalNodeID issues a fresh node identity. It runs when a peer
// rejects the join because the ID collides with its own — the typical cause
// is a node deployed by copying another node's data directory, which copies
// the stored node_id along with everything else.
func regenerateLocalNodeID() {
	localNodeMu.Lock()
	old := localNodeIDLocked()
	fresh := uuid.NewString()
	kvSet("node_id", fresh)
	localNodeIDCached = fresh
	selfRow.ID = fresh
	changed := old != "" && old != fresh
	if changed {
		// Re-point local records that referenced the old identity.
		db.Model(&Client{}).Where("home_node_id = ?", old).Update("home_node_id", fresh)
		db.Model(&Listener{}).Where("node_id = ?", old).Update("node_id", fresh)
		db.Model(&Task{}).Where("origin_node = ?", old).Update("origin_node", fresh)
	}
	localNodeMu.Unlock()

	// Logged outside the lock: addLog fans out into cluster events which
	// call localNodeID() and would deadlock on the held mutex.
	if changed {
		addLog("CLUSTER", fmt.Sprintf("NODE_ID_REGENERATED: %s -> %s", old[:8], fresh[:8]))
	}
}

func clusterInit() {
	localNodeID()

	// Reset peer status: connectivity is re-established by the heartbeat loop.
	db.Model(&ClusterNode{}).Where("status = ?", "online").Update("status", "offline")

	clusterEventHook = enqueueClusterEvent
	go clusterEventWorker()
	go clusterHeartbeatWorker()
	go clusterEventCleanupWorker()
	addLog("CLUSTER", fmt.Sprintf("CLUSTER_NODE_READY: %s", localNodeIDCached))
}

// ── Event emission ───────────────────────────────────────

func enqueueClusterEvent(eventType string, payload interface{}, targetNode string) {
	data, err := json.Marshal(payload)
	if err != nil {
		return
	}
	if targetNode != "" {
		if targetNode == localNodeID() {
			return
		}
		db.Create(&ClusterEvent{TargetNode: targetNode, Type: eventType, Payload: string(data), CreatedAt: time.Now()})
		return
	}
	var peers []ClusterNode
	db.Where("id != ?", localNodeID()).Find(&peers)
	for _, p := range peers {
		db.Create(&ClusterEvent{TargetNode: p.ID, Type: eventType, Payload: string(data), CreatedAt: time.Now()})
	}
}

// ── Outbound workers ─────────────────────────────────────

func clusterEventWorker() {
	for {
		time.Sleep(clusterEventInterval)
		var events []ClusterEvent
		if err := db.Where("sent_at IS NULL").Order("id asc").Limit(clusterEventBatch * 8).Find(&events).Error; err != nil {
			continue
		}
		if len(events) == 0 {
			continue
		}
		// Group by target node and push one batch per peer.
		batches := make(map[string][]ClusterEvent)
		for _, e := range events {
			batches[e.TargetNode] = append(batches[e.TargetNode], e)
		}
		for target, batch := range batches {
			clusterPushEvents(target, batch)
		}
	}
}

type clusterEventWire struct {
	ID      uint             `json:"id"`
	Type    string           `json:"type"`
	Payload *json.RawMessage `json:"payload"`
}

func clusterPushEvents(target string, batch []ClusterEvent) {
	var peer ClusterNode
	if err := db.First(&peer, "id = ?", target).Error; err != nil {
		return // unknown target (node removed); events age out via cleanup
	}

	wire := make([]clusterEventWire, 0, len(batch))
	for _, e := range batch {
		raw := json.RawMessage(e.Payload)
		wire = append(wire, clusterEventWire{ID: e.ID, Type: e.Type, Payload: &raw})
	}
	body, _ := json.Marshal(map[string]interface{}{"events": wire})

	resp, err := clusterRequest(peer, http.MethodPost, "/cluster/events", body)
	if err != nil {
		clusterMarkPeer(&peer, false)
		return
	}
	resp.Body.Close()
	clusterMarkPeer(&peer, true)

	now := time.Now()
	ids := make([]uint, 0, len(batch))
	for _, e := range batch {
		ids = append(ids, e.ID)
	}
	db.Model(&ClusterEvent{}).Where("id IN ?", ids).Update("sent_at", now)
}

func clusterMarkPeer(peer *ClusterNode, reachable bool) {
	now := time.Now()
	if reachable {
		if peer.Status != "online" {
			addLog("CLUSTER", fmt.Sprintf("NODE_ONLINE: %s (%s)", peer.Name, peer.URL))
		}
		db.Model(peer).Updates(map[string]interface{}{"status": "online", "last_seen": now})
		peer.Status = "online"
		peer.LastSeen = now
		return
	}
	if peer.Status == "online" && time.Since(peer.LastSeen) > clusterOfflineAfter {
		addLog("CLUSTER", fmt.Sprintf("NODE_OFFLINE: %s (%s)", peer.Name, peer.URL))
		db.Model(peer).Update("status", "offline")
		peer.Status = "offline"
	}
}

func clusterHeartbeatWorker() {
	for {
		var peers []ClusterNode
		db.Where("id != ?", localNodeID()).Find(&peers)
		for _, peer := range peers {
			go func(peer ClusterNode) {
				var clientCount, onlineCount int64
				db.Model(&Client{}).Where("home_node_id = ?", localNodeIDCached).Count(&clientCount)
				db.Model(&Client{}).Where("home_node_id = ? AND status = ?", localNodeIDCached, "online").Count(&onlineCount)
				body, _ := json.Marshal(map[string]interface{}{
					"name": selfRow.Name, "beacons": clientCount, "online": onlineCount,
				})
				resp, err := clusterRequest(peer, http.MethodPost, "/cluster/heartbeat", body)
				if err != nil {
					// The event push path also refreshes reachability; only
					// flip to offline when both have been quiet for a while.
					if time.Since(peer.LastSeen) > clusterOfflineAfter {
						clusterMarkPeer(&peer, false)
					}
					return
				}
				resp.Body.Close()
				clusterMarkPeer(&peer, true)
			}(peer)
		}
		time.Sleep(clusterHeartbeatInterval)
	}
}

func clusterEventCleanupWorker() {
	for {
		time.Sleep(1 * time.Hour)
		cutoff := time.Now().Add(-clusterEventMaxAge)
		db.Where("created_at < ?", cutoff).Delete(&ClusterEvent{})
	}
}

// clusterRequest sends an HMAC-signed request to a peer node.
func clusterRequest(peer ClusterNode, method, path string, body []byte) (*http.Response, error) {
	url := peer.URL + path
	req, err := http.NewRequest(method, url, bytes.NewReader(body))
	if err != nil {
		return nil, err
	}
	signClusterRequest(req, peer.Token, body)
	req.Header.Set("Content-Type", "application/json")
	return clusterHTTPClient.Do(req)
}

func clusterSignString(token, ts string, body []byte) string {
	mac := hmac.New(sha256.New, []byte(token))
	mac.Write([]byte(ts + "."))
	mac.Write(body)
	return hex.EncodeToString(mac.Sum(nil))
}

func signClusterRequest(req *http.Request, token string, body []byte) {
	ts := strconv.FormatInt(time.Now().Unix(), 10)
	req.Header.Set("X-Node-ID", localNodeID())
	req.Header.Set("X-Node-Timestamp", ts)
	req.Header.Set("X-Node-Sign", clusterSignString(token, ts, body))
}

